from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(HERE, "figures")
OUT = os.path.join(HERE, "甲骨文未释字考释报告.docx")

doc = Document()
st = doc.styles["Normal"]
st.font.name = "Times New Roman"
st.font.size = Pt(12)
st.element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
st.paragraph_format.line_spacing = 1.25
st.paragraph_format.first_line_indent = Pt(24)
for i, sz in ((1, 15), (2, 13)):
    s = doc.styles[f"Heading {i}"]
    s.font.name = "Times New Roman"
    s.font.size = Pt(sz)
    s.font.color.rgb = RGBColor(0, 0, 0)
    s.element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")


def H(t, lv=1):
    p = doc.add_heading(t, level=lv)
    p.paragraph_format.first_line_indent = Pt(0)
    return p


def P(t, indent=True, size=None):
    p = doc.add_paragraph()
    r = p.add_run(t)
    if size:
        r.font.size = Pt(size)
    if not indent:
        p.paragraph_format.first_line_indent = Pt(0)
    return p


def FIGURE(path, w, cap):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Pt(0)
    p.add_run().add_picture(path, width=Cm(w))
    c = doc.add_paragraph()
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.first_line_indent = Pt(0)
    r = c.add_run(cap)
    r.font.size = Pt(10.5)
    r.font.name = "Times New Roman"
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")


def TABLE(rows, widths=None):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    for i, row in enumerate(rows):
        for j, x in enumerate(row):
            c = t.cell(i, j)
            c.text = ""
            r = c.paragraphs[0].add_run(str(x))
            r.font.size = Pt(10.5)
            if i == 0:
                r.bold = True
    return t


